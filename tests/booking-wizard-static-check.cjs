const fs = require('node:fs');
const read = path => fs.readFileSync(path, 'utf8');
const html = read('public/customer.html');
const wizard = read('public/booking-wizard.js');
const css = read('public/booking-wizard.css');
const customerPages = read('public/customer-pages.js');
const customerShell = read('public/premium-shell.js');
const driverShell = read('apps/driver/public/premium-shell.js');
const driverPages = read('apps/driver/public/section-pages.js');
const assert = (condition, message) => { if (!condition) throw new Error(message); };
assert(html.includes('booking-wizard.js') && html.includes('booking-wizard.css'), 'Customer page must load the booking wizard JS and CSS.');
assert(['Collection & destination','Parcel & vehicle','Delivery options','Review & book'].every(label => wizard.includes(label)), 'The booking wizard must contain all four requested stages.');
assert(wizard.includes('form.noValidate = true') && wizard.includes('checkValidity()'), 'Wizard must validate the visible step without hidden-field focus traps.');
assert(wizard.includes('submit-counter-offer') && wizard.includes('booking-terms-accepted'), 'Final review must preserve the existing counteroffer and protection acknowledgement controls.');
assert(customerPages.includes("root.addEventListener('click'") && customerPages.includes("link.dataset.page"), 'Customer page links must use delegated in-app navigation.');
assert(!customerShell.includes('nav.innerHTML ='), 'Customer premium shell must not replace page links after listeners attach.');
assert(!driverShell.includes('nav.innerHTML ='), 'Driver premium shell must not replace page links after listeners attach.');
assert(driverPages.includes("link.dataset.page || 'home'"), 'Driver section pages must retain their page navigation handler.');
assert(css.includes('#booking-form .booking-step') && css.includes('background:#10151d'), 'Booking wizard must use the dark premium card layout.');
console.log('Customer booking wizard and in-app navigation checks passed.');
